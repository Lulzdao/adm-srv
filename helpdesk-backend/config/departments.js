// Единый список отделов-исполнителей.
//
// СВОЙ СПИСОК — НЕ ЗДЕСЬ. Этот файл приходит с обновлением и при каждом
// обновлении перезаписывается. Чтобы добавить отдел, скопируйте файл рядом
// под именем departments.local.js и правьте копию: если она есть, платформа
// берёт список из неё целиком, а обновление её не трогает (см. deploy/update.ps1).
//
// Чтобы добавить новую группу (например бухгалтерию), достаточно дописать
// один объект в массив и перезапустить сервер — дальше распространяется само:
//   - таблица categories (номера заявок вида БУХ-0001) — досеется при
//     старте сервера, ничего руками создавать не нужно;
//   - маршрутизация уведомлений о новых заявках;
//   - права доступа (эта роль видит очередь своего отдела + свои заявки
//     в любом отделе, остальные её заявки не видят);
//   - выпадающий список отделов при создании заявки и в фильтре списка;
//   - блок настройки AD-группы в панели администрирования.
//
// role — техническое имя роли в БД/сессии, латиницей, без пробелов.
// prefix — то, что печатается перед номером заявки (БУХ-0001).
// name — то, что видит пользователь (в выпадающих списках, в колонке "От кого" и т.д.),
//        также хранится как имя строки в таблице categories.
//
// hint, icon, color — только оформление плитки отдела на экране новой заявки.
// Все три необязательны: без них плитка нарисуется с общим значком и цветом
// из общего набора, ничего не сломается. Но подпись стоит написать: «ЕГРПО»
// или «ХОЗ» человеку со стороны ни о чём не говорят, и именно строка с
// примерами решает, куда он отправит заявку.
//
// icon — имя из набора значков в public/app.js (ICON_PATHS). Для отделов
// заранее заготовлены: monitor (техника), pen (ремонт и хозяйство),
// doc (документы и справки), receipt (деньги и отчётность), users (люди),
// key (доступ и режим), phone, shield, box. Незнакомое имя — значок box.
//
// color — цвет значка, из фирменной палитры (см. public/styles.css):
// #0A61AE тёмно-голубой, #663AB5 тёмно-сиреневый, #008F9F тёмно-изумрудный,
// #C25A18 оранжевый, #E7004B тёмно-розовый, #5A5A5A серый.
