// Свой список на сервере — config/departments.local.js. Ошибка в нём не должна
// молча возвращать встроенный список (заявки новых отделов потеряли бы очередь),
// поэтому битый файл останавливает запуск с понятной причиной.
function load() {
  const fs = require("fs");
  const local = require("path").join(__dirname, "departments.local.js");
  if (!fs.existsSync(local)) return DEFAULT_DEPARTMENTS;
  const list = require(local);
  const bad = !Array.isArray(list) || !list.length
    || list.some((d) => !d || !d.name || !d.prefix || !d.role || !/^[a-z0-9_]+$/i.test(d.role));
  if (bad) throw new Error(`config/departments.local.js: нужен непустой список отделов, у каждого name, prefix и role (латиницей)`);
  return list;
}

module.exports = load();
