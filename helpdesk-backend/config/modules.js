// Реестр встроенных модулей платформы (Сертвивер, журнал звонков и т.д.).
// Каждый модуль — самостоятельный процесс на своём localhost-порту, снаружи
// сети не виден вообще. Платформа проксирует запросы к нему только тем, кто
// уже вошёл и обладает нужной ролью — сам модуль про логин ничего не знает
// (см. MIGRATION-CERTVIEWER.md).
//
// path   — префикс, под которым модуль встроен в платформу
// target — адрес процесса модуля (обязательно 127.0.0.1, не 0.0.0.0/реальный IP)
// roles  — кому виден пункт меню и разрешён доступ; 'it' покрывает почти все
//          случаи, но при необходимости можно добавить роли отделов
// label  — подпись пункта меню в сайдбаре
// views  — если у модуля несколько внутренних страниц (как у журнала
//          звонков — Журнал/Статистика/Справочник), перечисляем их здесь:
//          {id, label, sub}, где sub — путь относительно path (пустая
//          строка "" — корень модуля). Сама навигация внутри модуля при
//          этом должна быть скрыта — переключение живёт в сайдбаре
//          платформы, модуль о нём ничего не знает (просто открывается
//          нужный внутренний путь через iframe).

