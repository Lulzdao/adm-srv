const modules = require("../config/modules");

// ============================================================================
//  Чтение данных из встроенных модулей
//
//  Платформа ТЯНЕТ, модули не знают про оповещения вовсе. Это сознательный
//  выбор из трёх возможных: если бы модули толкали события сами, у каждого
//  появился бы свой планировщик, свой клиент и свой общий секрет, а «Искру»
//  трогать нельзя вообще — она приезжает из чужого репозитория. Читать чужие
//  файлы баз напрямую тоже нельзя: платформа намертво привязалась бы к их
//  внутренним схемам, и переименованная в модуле колонка молча ломала бы
//  рассылку.
//
//  Опрос ничего не требует от модулей потому, что за платформой они и так
//  считают всякий запрос доверенным: Сертвивер при BEHIND_GATEWAY пропускает
//  запрос без проверки, у журнала звонков авторизации нет вовсе, и оба слушают
//  только 127.0.0.1. Снаружи туда не достучаться.
// ============================================================================

const BY_ID = new Map(modules.map((m) => [m.id, m]));

// Модуль может лежать (перезапуск, обновление, NSSM его придушил). Это не
// авария платформы: пропущенный обход наверстается на следующем часе, потому
// что порог считается от даты, а не от того, что мы его «уже смотрели».
const TIMEOUT_MS = 8000;

async function fetchJson(moduleId, path) {
  const mod = BY_ID.get(moduleId);
  if (!mod) throw new Error(`Модуль «${moduleId}» не описан в config/modules.js`);

  const url = mod.target.replace(/\/$/, "") + path;
  let res;
  try {
    res = await fetch(url, {
      signal: AbortSignal.timeout(TIMEOUT_MS),
      headers: { Accept: "application/json" },
    });
  } catch (err) {
    const reason = err.name === "TimeoutError" ? "не ответил вовремя" : err.message;
    throw new Error(`Модуль «${mod.label}» недоступен (${reason})`);
  }

  if (!res.ok) {
    throw new Error(`Модуль «${mod.label}» ответил ${res.status} на ${path}`);
  }
  try {
    return await res.json();
  } catch {
    // Чаще всего это HTML страницы логина: модуль решил, что запрос не от
    // платформы. Тогда виноват BEHIND_GATEWAY, и сказать это надо прямо.
    throw new Error(
      `Модуль «${mod.label}» вернул не JSON на ${path} — проверьте, что он запущен с BEHIND_GATEWAY=true`
    );
  }
}

module.exports = { fetchJson };
