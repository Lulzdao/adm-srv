'use strict';

const os = require("node:os");
const path = require("node:path");

// ============================================================================
//  Тесты не читают настоящий .env
//
//  config/config.js загружает .env из рабочего каталога, а тесты запускаются
//  из того же helpdesk-backend, где на рабочей машине лежит настоящий .env. Его
//  значения смешивались с тем, что выставляет сам тест, и итог зависел от
//  машины: с .env падали проверки почты локальных учёток (пустое LOCAL_*_EMAIL=
//  в файле снимало переменную, выставленную тестом), без .env — проверка прав
//  аварийной учётки (она молча опиралась на хэш пароля из чьего-то .env).
//
//  Указываем конфигу несуществующий файл: dotenv тогда не загружает ничего, и
//  каждый тест видит только то окружение, которое задал сам.
//
//  Подключается и через --require в npm test (для всех наборов разом), и из
//  tempDb.js — чтобы одиночный запуск `node --test test/x.test.js` вёл себя так же.
// ============================================================================

process.env.HELPDESK_ENV_FILE = path.join(os.tmpdir(), "adm-srv-test-нет-такого.env");

// Резервная копия баз (задание планировщика) по умолчанию берёт настоящие базы
// рядом с платформой и пишет в <корень>\backups — то есть в рабочую копию. Тесты,
// которые гоняют все задания планировщика, делали бы это на самом деле. Пустой
// список баз: задание выполняется, но ничего не копирует. Тест самой копии
// (backup.test.js) задаёт свои базы и каталог.
process.env.BACKUP_DATABASES = "-";
process.env.BACKUP_DIR = path.join(os.tmpdir(), "adm-srv-test-backups-не-используется");
