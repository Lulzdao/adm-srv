'use strict';

const { buildXlsx } = require("../../services/xlsx");

// ============================================================================
//  Таблица «как из ЦСОД» для тестов бюллетеней
//
//  Устроена как настоящая выгрузка индексов производства: заголовок с месяцем
//  в первой строке, наименование в A, код в B, три значения в C–E; разделы
//  ОКВЭД — буквами и ЗАГЛАВНЫМИ, виды деятельности — двумя цифрами, ниже —
//  подгруппы с точками. Числа выдуманы.
//
//  В конце — много строк с длинными разными наименованиями: в .xls общий
//  список строк книги (SST) тогда не влезает в одну запись и продолжается в
//  записях CONTINUE — самое хрупкое место формата.
//
//  test/fixtures/bulletin-sample.xls — эта же таблица, пересохранённая в .xls:
//    node -e 'fs.writeFileSync("t.xlsx", require("./test/helpers/bulletinTable").xlsx())'
//    soffice --headless --convert-to xls t.xlsx
// ============================================================================

const TITLE = "Индексы производства по видам экономической деятельности по полному кругу организаций за март 2031 года";

const DATA = [
  ["Промышленное производство (промышленность)", "102", 101.5, 98.25, 102.3],
  ["ДОБЫЧА ПОЛЕЗНЫХ ИСКОПАЕМЫХ", "B", 97.4, 101.1, 99],
  ["Добыча угля", "05", 90.2, 95.5, 93.1],
  ["Добыча угля подземным способом", "05.1", 90.2, 95.5, 93.1],
  ["ОБРАБАТЫВАЮЩИЕ ПРОИЗВОДСТВА", "C", 104.6, 112.4, 103.8],
  ["Производство пищевых продуктов", "10", 99.9, 104, 100.4],
  ["Переработка и консервирование мяса", "10.1", 99.1, 103, 100.2],
  ["Производство напитков", "11", 250.3, 87.6, 121],
  ["Производство одежды", "14", 77.7, 199.99, 85.05],
  ["ОБЕСПЕЧЕНИЕ ЭЛЕКТРИЧЕСКОЙ ЭНЕРГИЕЙ, ГАЗОМ И ПАРОМ; КОНДИЦИОНИРОВАНИЕ ВОЗДУХА", "D", 108, 96.3, 104.4],
  ["Обеспечение электрической энергией, газом и паром; кондиционирование воздуха", "35", 108, 96.3, 104.4],
  ["ВОДОСНАБЖЕНИЕ; ВОДООТВЕДЕНИЕ, ОРГАНИЗАЦИЯ СБОРА И УТИЛИЗАЦИИ ОТХОДОВ", "E", 102, 100, 1000],
  ["Забор, очистка и распределение воды", "36", 0, 5.6, 0],
];

const FILLER = Array.from({ length: 150 }, (_, i) =>
  [`Строка-заполнитель номер ${i + 1}: длинное наименование вида деятельности, чтобы общий список строк книги был большим`, `99.${i + 1}`, i + 0.5, null, null]);

function rows() {
  return [...DATA, ...FILLER];
}

/** Книга .xlsx: первая строка — заголовок (как у ЦСОД), дальше данные. */
function xlsx({ title = TITLE, data = rows() } = {}) {
  return buildXlsx([{
    name: "Таблица 1",
    columns: [{ title }, { title: "Код ОКВЭД" }, { title: "1" }, { title: "2" }, { title: "3" }],
    rows: data,
  }]);
}

module.exports = { TITLE, DATA, FILLER, rows, xlsx };
