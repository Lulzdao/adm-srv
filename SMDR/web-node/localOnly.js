// ============================================================================
//  Запросы — только от платформы и с самого сервера
//
//  За платформой модуль слушает 127.0.0.1 и своего входа не имеет: вход и роль
//  проверяет платформа, а на сервер заходят только администраторы. Но в DEPLOY.md
//  платформу открывают в браузере прямо на сервере — и тогда страница ЛЮБОГО
//  сайта, открытого в том же браузере, может сама отправить запрос на
//  http://127.0.0.1:<порт>: форма с чужой страницы дошла бы до модуля и была бы
//  выполнена (загрузка файлов, правка справочника). А через DNS rebinding — чужой
//  домен, указывающий на 127.0.0.1, — такая страница могла бы и прочитать ответ.
//
//  Ключ между платформой и модулями этого не лечил бы лучше, а настроек добавил
//  бы (решение 2026-09-27: сервер один, заходят только администраторы ИТ). Хватает
//  двух проверок, которые законные запросы проходят сами:
//    - Host — адрес самого сервера (127.0.0.1 / localhost). Прокси платформы
//      (changeOrigin) и её планировщик ходят именно так; при DNS rebinding в Host
//      стоит чужой домен.
//    - Sec-Fetch-Site не «cross-site». Браузер (Chromium 76+) ставит его сам, и
//      подделать страница его не может; у прокси он «same-origin», у
//      планировщика и curl его нет вовсе.
//
//  Файл одинаковый в CERTVIEWER и SMDR/web-node: модули — отдельные процессы без
//  общей библиотеки. Правите один — правьте и второй.
// ============================================================================

const LOCAL_HOSTS = new Set(['127.0.0.1', 'localhost', '[::1]']);

/** Имя хоста из заголовка Host без порта; IPv6 — в квадратных скобках, как пришло. */
function hostName(hostHeader) {
  const h = String(hostHeader || '').trim().toLowerCase();
  if (h.startsWith('[')) return h.slice(0, h.indexOf(']') + 1);
  return h.split(':')[0];
}

function localOnly(req, res, next) {
  if (!LOCAL_HOSTS.has(hostName(req.headers.host))) {
    return res.status(403).json({ error: 'Модуль принимает запросы только через платформу' });
  }
  if (String(req.headers['sec-fetch-site'] || '').toLowerCase() === 'cross-site') {
    return res.status(403).json({ error: 'Запрос со стороннего сайта отклонён' });
  }
  next();
}

module.exports = { localOnly, hostName };
