// node:sqlite — встроенный в Node модуль (как у платформы и Сертвивера). Раньше здесь был
// better-sqlite3: нативный модуль, который собирается компилятором под конкретную версию Node.
// На закрытом контуре компилятора нет, и node_modules приходилось переносить с машины с той же
// версией Node — иначе служба падала с NODE_MODULE_VERSION. Встроенному модулю собирать нечего.
// Нужен Node 22.13+ (там node:sqlite без флагов и есть db.function).
const { DatabaseSync } = require('node:sqlite');
const path = require('path');

const DB_FILE = path.join(__dirname, '..', 'smdr.db');
const db = new DatabaseSync(DB_FILE);
// Ждать занятую запись — первым делом, до любого обращения к файлу: раньше оно стояло после
// переключения в WAL, и база, которую в момент запуска держал коллектор или DB Browser, роняла
// веб-часть сразу (проверено на стенде). Значение 10 с — см. ниже, у переключения в WAL.
db.exec('PRAGMA busy_timeout = 10000');

// WAL: читатель и писатель перестают мешать друг другу.
//
// Базу делят два процесса: сюда пишет Collector.Py, отсюда читает веб-часть. В
// обычном (rollback) журнале длинное чтение блокирует вставку целиком, а любая
// ошибка базы в коллекторе вылетает в главный цикл, рвёт TCP-сессию с АТС и
// ждёт пять секунд до переподключения. Всё, что АТС отдаст за эти пять секунд,
// теряется навсегда: SMDR не переспрашивают. WAL убирает саму причину.
//
// Режим журнала записан в файле базы, поэтому достаточно выставить его один
// раз — но выставляем и здесь, и в коллекторе: кто первый поднялся, тот и
// починил, а порядок запуска служб не гарантирован.
// Испорченный файл останавливает веб-часть с подсказкой (как у платформы и Сертвивера), а не стеком.
try {
  db.exec('PRAGMA journal_mode = WAL');
} catch (err) {
  const code = err && err.errcode;
  if (code === 26 || code === 11) {
    console.error(`[остановка] Файл базы ${DB_FILE} повреждён или это не база SQLite (${err.message}).\n` +
      '            Остановите веб-часть и коллектор, переименуйте файл (и -wal, -shm рядом) и положите на его место\n' +
      '            последнюю копию smdr-ГГГГ-ММ.db из папки резервных копий платформы (DEPLOY.md, «Резервные копии баз»).');
    process.exit(1);
  }
  if (code === 5 || code === 6) {
    console.error(`[остановка] База ${DB_FILE} занята другой программой дольше 10 секунд (${err.message}).\n` +
      '            Закройте программу, в которой она открыта (DB Browser и т.п.), — служба перезапустится сама.');
    process.exit(1);
  }
  throw err;
}
// Повреждение внутри базы запуск не останавливает — читается то, до чего оно не дотянулось, — но
// пишется в журнал громко. quick_check на базе за год (~300 тыс. звонков) — доли секунды.
{
  let problems;
  try {
    const rows = db.prepare('PRAGMA quick_check').all().map((r) => Object.values(r)[0]);
    problems = rows.length === 1 && rows[0] === 'ok' ? null : rows.slice(0, 5).join('; ');
  } catch (err) {
    problems = err.message;
  }
  if (problems) {
    console.error(`[внимание] База ${DB_FILE} повреждена: ${problems}\n` +
      '           Журнал звонков работает, но часть данных может не читаться. Восстановите базу из резервной копии.');
  }
}

db.exec(`
  CREATE TABLE IF NOT EXISTS employees (
    ext TEXT PRIMARY KEY,
    fio TEXT
  )
`);

// Индексы под фактические запросы. Таблицу calls создаёт коллектор и делает это
// без единого индекса, поэтому заводим их здесь: веб-часть — единственный, кто
// по ним ходит. Замер на 300 тыс. строк (примерно год работы):
//
//   страница журнала   35,2 мс -> 0,11 мс
//   счётчик по типу    18,9 мс -> 2,5 мс
//   сводка по людям    82,9 мс -> 22,4 мс
//
// Дашборд опрашивает себя раз в 5 секунд на каждую открытую вкладку, а
// запросы к базе синхронные: сэкономленное здесь — это время, которое процесс
// не проводит заблокированным.
//
// Таблицу calls заводит коллектор, и схему её дублировать здесь нельзя — иначе
// два описания разъедутся. Поэтому индексы ставим, только если таблица уже
// есть: при первом запуске веб-части на пустой машине коллектор ещё мог не
// создать её, и CREATE INDEX упал бы, не дав серверу подняться вовсе.
if (db.prepare("SELECT 1 FROM sqlite_master WHERE type='table' AND name='calls'").get()) {
  db.exec(`
    CREATE INDEX IF NOT EXISTS idx_calls_dt ON calls(call_dt DESC);
    CREATE INDEX IF NOT EXISTS idx_calls_direction ON calls(direction);
    CREATE INDEX IF NOT EXISTS idx_calls_ext ON calls(ext);
  `);
}

// Встроенный LOWER() в SQLite понимает только латиницу.
// Регистрируем свою функцию на JS — toLowerCase() корректно работает с кириллицей.
db.function('lower_ru', { deterministic: true }, (str) => {
  if (str === null || str === undefined) return null;
  return String(str).toLowerCase();
});

// Длительность и ожидание лежат в базе СТРОКАМИ (`00:03'41`, `0'04`) — так их
// отдаёт АТС, и схему коллектора мы не трогаем. Сравнить «дольше пяти минут»
// с такой строкой в SQL нельзя, поэтому переводим её в секунды своей
// функцией — тем же приёмом, что и lower_ru выше.
//
// Индексом такое сравнение не пользуется, и это нормально: фильтр по
// длительности всегда идёт вторым после диапазона дат, а тот по индексу и
// отбирает.
const { durationToSeconds } = require('./duration');
db.function('dur_sec', { deterministic: true }, (str) => durationToSeconds(str));

module.exports = db;
