'use strict';

// Длительность и время ожидания АТС отдаёт СТРОКОЙ, а не числом:
//   duration — `ЧЧ:ММ'СС`, например 00:03'41
//   ring     — `М'СС`,     например 0'04 (часов в нём не бывает)
// (см. SMDR/README.md, раздел про поля записи).
//
// Менять формат в базе нельзя: туда пишет Collector.Py, и его схема —
// не наша. Поэтому строку разбираем при чтении.

/**
 * Строка АТС в секунды. Понимает обе формы, которые встречаются в базе,
 * и голое число секунд на всякий случай. Всё непонятное — 0.
 *
 * Прежняя реализация в server.js принимала ТОЛЬКО `ЧЧ:ММ'СС`, и `ring`
 * вида `0'04` она молча превращала в ноль. На статистику это не влияло —
 * там считалась одна только duration, — но фильтру «ожидание дольше»
 * такая функция не годится совсем.
 */
function durationToSeconds(str) {
  if (typeof str !== 'string') return 0;
  const s = str.trim();
  if (!s) return 0;

  let m = /^(\d{1,3}):(\d{1,2})'(\d{1,2})$/.exec(s);
  if (m) return Number(m[1]) * 3600 + Number(m[2]) * 60 + Number(m[3]);

  m = /^(\d{1,3})'(\d{1,2})$/.exec(s);
  if (m) return Number(m[1]) * 60 + Number(m[2]);

  m = /^(\d{1,6})$/.exec(s);
  if (m) return Number(m[1]);

  return 0;
}

/**
 * То же самое, но для того, что человек напечатал в поле фильтра.
 *
 * Формат здесь другой и намеренно свободный: в поле «разговор дольше»
 * подписано «мм:сс», и никто не станет ставить апостроф, как это делает АТС.
 * Принимаем `5` (секунды), `5:30`, `1:05:30` и заодно форму самой АТС —
 * человек мог скопировать значение прямо из таблицы.
 *
 * Возвращает null, если разобрать не удалось: это отличает «поле пустое или
 * заполнено ерундой» от «ноль секунд», а ноль как порог означал бы «показать
 * вообще всё» и фильтр молча перестал бы работать.
 */
function inputToSeconds(str) {
  if (typeof str !== 'string') return null;
  const s = str.trim();
  if (!s) return null;

  let m = /^(\d{1,3}):(\d{1,2}):(\d{1,2})$/.exec(s);
  if (m) return Number(m[1]) * 3600 + Number(m[2]) * 60 + Number(m[3]);

  m = /^(\d{1,3}):(\d{1,2})$/.exec(s);
  if (m) return Number(m[1]) * 60 + Number(m[2]);

  m = /^(\d{1,6})$/.exec(s);
  if (m) return Number(m[1]);

  // Форма АТС — на случай, если значение скопировали из таблицы.
  const изБазы = durationToSeconds(s);
  return изБазы > 0 ? изБазы : null;
}

module.exports = { durationToSeconds, inputToSeconds };
