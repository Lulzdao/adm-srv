// Где открыть новое окно чата, чтобы оно не легло ровно поверх уже открытого (просьба пользователя
// 2026-10-22). Все чаты открываются в одном месте — в запомненном или по центру экрана, — и второй
// закрывал первый целиком: казалось, что открылось одно окно. Теперь, если на этом месте уже стоит
// окно, новое сдвигается вниз-вправо на STEP, как «лесенка» в Windows. Окно, которое человек
// передвинул сам, место не занимает — новое откроется на обычном месте.
//
// Чистая функция: на входе желаемое место, размер, где стоят открытые окна и рабочая область экрана,
// на выходе — место нового окна.

const STEP = 28; // примерно высота заголовка: у сдвинутого окна виден заголовок того, что под ним
const SAME = 8;  // окна ближе этого по обеим осям считаем стоящими на одном месте

function cascadePosition(pos, size, occupied, area, step = STEP) {
  const taken = (p) => occupied.some((o) => Math.abs(o.x - p.x) < SAME && Math.abs(o.y - p.y) < SAME);
  let p = { x: pos.x, y: pos.y };
  let restarts = 0;
  // Ограничение числа шагов — от зацикливания: на экране не бывает столько окон в одной лесенке.
  for (let i = 0; i < 40 && taken(p); i++) {
    p = { x: p.x + step, y: p.y + step };
    // Лесенка упёрлась в край экрана — начинаем новую от левого верхнего угла рабочей области,
    // каждый раз чуть правее, чтобы не лечь на прежнюю.
    if (p.x + size.width > area.x + area.width || p.y + size.height > area.y + area.height) {
      restarts += 1;
      p = { x: area.x + restarts * step, y: area.y };
    }
  }
  return p;
}

// Центр рабочей области — туда Windows и сама ставит окно без координат.
function centerIn(area, size) {
  return {
    x: area.x + Math.max(0, Math.round((area.width - size.width) / 2)),
    y: area.y + Math.max(0, Math.round((area.height - size.height) / 2)),
  };
}

module.exports = { cascadePosition, centerIn, STEP };
