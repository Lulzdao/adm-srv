// Адрес, откуда собранное приложение забирает обновления. Берётся из того же config.js, что и
// адрес сервера, — чтобы он не задваивался и не разъезжался при переезде сервера.
//
// Это ЗАПАСНОЕ значение, зашиваемое в установщик при сборке. В работе клиент подставляет адрес
// заново перед каждой проверкой, исходя из того, куда он реально подключён (см. updateFeedUrl в
// main.js): адрес сервера можно поменять на конкретной машине по Ctrl+S, и обновления обязаны
// следовать за ним, а не искать их там, где сервер стоял на момент сборки установщика.
//
// Отдельным файлом, а не полем в base.js: всё, что экспортирует base.js, уходит в electron-builder
// как конфигурация, и лишнее поле там неуместно.

const { SERVER_URL } = require('../config');

module.exports = (track) => `${String(SERVER_URL).replace(/\/+$/, '')}/updates/${track}`;
