// Сборка для Windows 7 и 8.1.
//
// Electron 22.3.27 — последняя версия, работающая на этих системах: начиная с 23 поддержка Win7/8.1
// в Electron убрана. Поэтому версия здесь ЗАМОРОЖЕНА и поднимать её нельзя, пока такие машины
// остаются в парке. Эта же версия стоит в devDependencies — то есть `npm start` при разработке
// запускает именно её, и несовместимость с Win7 всплывает сразу у разработчика, а не через месяц
// у сотрудника. Это и есть замена «отдельной ветки под Win7» из первоначального плана.
//
// Сборка рассчитана на самую старую поддерживаемую систему, поэтому запускается и на Windows 10 —
// проверки версии ОС при установке здесь намеренно нет (в отличие от win10.js).

const base = require('./base');
const feedUrl = require('./feed');

module.exports = {
  ...base,
  electronVersion: '22.3.27',
  directories: { output: 'dist/win7' },
  // Свой адрес обновлений у каждой сборки — иначе клиент на Windows 7 рано или поздно скачает
  // сборку с Electron, который на нём не запускается. Наличие publish обязательно и по другой
  // причине: без него electron-builder не создаёт latest.yml, а без latest.yml проверять нечего.
  publish: [{ provider: 'generic', url: feedUrl('win7') }],
  // Метка попадает в package.json внутри собранного приложения — по ней клиент показывает в
  // настройках, какая именно сборка установлена (см. get-app-info в main.js). Нужна поддержке:
  // достаточно спросить у человека строку внизу панели настроек, а не выяснять версию Windows.
  extraMetadata: { buildTrack: 'win7' },
  // Без ${arch} в имени — и это принципиально, а не косметика. С ним electron-builder собрал бы
  // ТРИ установщика на трек: общий (обе архитектуры внутри) плюс отдельные x64 и ia32. А на Windows
  // latest.yml всегда один, и electron-updater выбирает из него просто первый .exe, не разбирая
  // разрядность (см. findFile в его Provider.js) — то есть 32-битная машина могла бы получить на
  // обновление 64-битный установщик. Один общий установщик снимает вопрос: он и так содержит обе
  // архитектуры и сам ставит нужную. Платим за это размером файла, что для локальной сети неважно.
  artifactName: 'iskra-setup-win7-${version}.${ext}',
};
