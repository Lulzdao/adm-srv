// Сборка для Windows 10 и новее.
//
// Смысл отдельного трека — современный Chromium: Electron 22 не получает обновлений безопасности
// с середины 2023 года, а окна клиента отображают текст, присланный другими людьми. Плюс на новых
// системах часть здешних обходов (эмодзи-картинки, отключение аппаратного ускорения) не нужна.
//
// Версию ниже можно и нужно периодически поднимать — это единственная строка, которую надо менять.
// Electron поддерживает три последних мажорных выпуска, так что ориентир — оставаться в этом окне.
// После подъёма ОБЯЗАТЕЛЬНО прогнать сборку на реальной Windows 10: здесь меняется весь рантайм
// (Chromium + Node), и проверить это чем-то, кроме запуска, нельзя.

const base = require('./base');
const feedUrl = require('./feed');

module.exports = {
  ...base,
  electronVersion: '43.4.1',
  directories: { output: 'dist/win10' },
  // Свой адрес обновлений — см. комментарий в win7.js.
  publish: [{ provider: 'generic', url: feedUrl('win10') }],
  extraMetadata: { buildTrack: 'win10' },
  artifactName: 'iskra-setup-win10-${version}.${ext}', // без ${arch} — см. пояснение в win7.js
  nsis: {
    ...base.nsis,
    // Отказ установиться на Windows старше 10 — см. сам файл. Разными именами установщиков
    // ограничиваться не стоит: если такую сборку поставить на Win7, приложение просто не
    // запустится, и разбираться в этом будет некому.
    include: 'build-config/installer-win10.nsh',
  },
};
