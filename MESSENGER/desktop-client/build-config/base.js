// Общая часть конфигурации сборки установщика. Отдельно от package.json, потому что сборок две —
// под Windows 7/8.1 и под Windows 10+ (см. win7.js и win10.js рядом). Различаются они только
// версией Electron, именем файла установщика и меткой трека; всё остальное — здесь, в одном месте,
// чтобы две сборки не разъезжались по мелочам.
//
// Почему именно так, а не две ветки git (как предполагал первоначальный план в CONCEPT-roadmap.md):
// версия Electron — это параметр СБОРКИ, а не свойство исходного кода. electron-builder умеет
// собирать с любой версией через electronVersion, независимо от того, что стоит в node_modules.
// Значит, обе сборки всегда собираются из одного и того же коммита, и «забыть перенести
// исправление во вторую ветку» физически невозможно.

module.exports = {
  // productName задаёт имя ярлыка, папки установки и запись в "Программы и компоненты".
  // Путь к данным пользователя (%APPDATA%\<имя>) от него НЕ зависит — Electron берёт имя из
  // package.json приложения (см. productName там же), а electron-builder туда ничего не
  // дописывает, кроме extraMetadata. Проверено запуском: app.getName() возвращает именно то,
  // что стоит в package.json.
  //
  // appId — идентификатор в реестре Windows. По нему установщик понимает, что ставит новую версию
  // ТОГО ЖЕ приложения, а не второе рядом. Менять его после того, как сборку раздали людям, нельзя:
  // у них останется старая копия в "Программы и компоненты" и второй ярлык.
  appId: 'ru.lipetskstat.iskra',
  productName: 'Искра',

  win: {
    icon: 'build/icon.ico',
    // 32-битные сборки Electron выпускаются до сих пор (проверено вплоть до 43.x), поэтому обе
    // ветки собираются и под x64, и под ia32 — в парке ещё встречаются 32-битные Windows.
    target: [{ target: 'nsis', arch: ['x64', 'ia32'] }],
  },

  nsis: {
    oneClick: false,
    allowToChangeInstallationDirectory: true,
    createDesktopShortcut: true,
    createStartMenuShortcut: true,
    // Брендинг ассистированного установщика (доступен только при oneClick: false выше).
    // installerHeader — полоса 150×57 на внутренних страницах мастера (выбор папки, прогресс).
    // installerSidebar — картинка 164×314 на экранах приветствия и финиша, тот же файл берётся
    // и для деинсталлятора (uninstallerSidebar не задан — electron-builder сам подставит этот же).
    // Указаны явно, а не оставлены на конвенцию по умолчанию (electron-builder и без этого нашёл
    // бы файлы с такими именами в build/) — чтобы не полагаться на негласное соглашение об именах.
    installerHeader: 'build/installerHeader.bmp',
    installerSidebar: 'build/installerSidebar.bmp',
  },

  // Белый список: всё, чего здесь нет, в установщик не попадает. Поэтому сама папка build-config/
  // (и её .nsh) в приложение не упаковывается — она нужна только на машине, где идёт сборка.
  files: [
    'main.js',
    'preload.js',
    'config.js',
    'renderer/**/*',
    'tray-icon.png',
    'build/icon.ico',
    // Корневой сертификат домена — нужен главному процессу, чтобы Node доверял серверу по https
    // (см. trustOrganizationCa в main.js). Публичный файл, секрета не содержит.
    'rosstat-root-ca.crt',
  ],
};
