// Общая часть конфигурации сборки установщика. Отдельно от package.json, потому что сборок две —
// под Windows 7/8.1 и под Windows 10+ (см. win7.js и win10.js рядом). Различаются они только
// версией Electron, именем файла установщика и меткой трека; всё остальное — здесь, в одном месте,
// чтобы две сборки не разъезжались по мелочам.
//
// Почему именно так, а не две ветки git (как предполагал первоначальный план в CONCEPT-roadmap.md):
// версия Electron — это параметр СБОРКИ, а не свойство исходного кода. electron-builder умеет
// собирать с любой версией через electronVersion, независимо от того, что стоит в node_modules.
// Значит, обе сборки всегда собираются из одного и того же коммита, и «забыть перенести
// исправление во вторую ветку» физически невозможно.

module.exports = {
  // ВНИМАНИЕ: productName — это не только имя ярлыка и папки установки. От него зависит путь к
  // данным пользователя (%APPDATA%\<productName>): там лежит settings.json (в том числе адрес
  // сервера, заданный вручную по Ctrl+S) и localStorage с токеном входа. Переименование здесь
  // означает, что у ВСЕХ сотрудников сбросятся настройки и потребуется войти заново.
  // Если однажды переименовывать в «Искра» — делать это отдельной задачей, с переносом старой
  // папки данных при первом запуске, а не заодно с чем-то ещё.
  appId: 'com.yourorg.minimessenger',
  productName: 'Мини-мессенджер',

  win: {
    icon: 'build/icon.ico',
    // 32-битные сборки Electron выпускаются до сих пор (проверено вплоть до 43.x), поэтому обе
    // ветки собираются и под x64, и под ia32 — в парке ещё встречаются 32-битные Windows.
    target: [{ target: 'nsis', arch: ['x64', 'ia32'] }],
  },

  nsis: {
    oneClick: false,
    allowToChangeInstallationDirectory: true,
    createDesktopShortcut: true,
    createStartMenuShortcut: true,
  },

  // Белый список: всё, чего здесь нет, в установщик не попадает. Поэтому сама папка build-config/
  // (и её .nsh) в приложение не упаковывается — она нужна только на машине, где идёт сборка.
  files: [
    'main.js',
    'preload.js',
    'config.js',
    'renderer/**/*',
    'tray-icon.png',
    'build/icon.ico',
  ],
};
